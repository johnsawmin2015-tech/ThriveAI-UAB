import type {
  BusinessProfile,
  CategoryTotal,
  MMK,
  MonthlyFinancialRecord,
} from "@/types";

const categoryTotals = (
  values: Readonly<Record<string, MMK>>,
): readonly CategoryTotal[] =>
  Object.entries(values).map(([category, amountMmk]) => ({
    category,
    amountMmk,
  }));

const monthlyRecord = (
  month: MonthlyFinancialRecord["month"],
  revenueByCategory: Readonly<Record<string, MMK>>,
  expensesByCategory: Readonly<Record<string, MMK>>,
  cashInflowMmk: MMK,
  cashOutflowMmk: MMK,
): MonthlyFinancialRecord => ({
  month,
  revenueByCategory: categoryTotals(revenueByCategory),
  expensesByCategory: categoryTotals(expensesByCategory),
  cashInflowMmk,
  cashOutflowMmk,
});

